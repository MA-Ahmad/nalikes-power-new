export function MobileBottomNavbar() {
  const pathname = usePathname()
  const isMobile = useIsMobile()
  const [shouldHide, setShouldHide] = useState(false)

  useEffect(() => {
    if (typeof window !== 'undefined') {
      const hostname = window.location.hostname
      const isPowerWin =
        hostname === 'power.win' || hostname === 'www.power.win'
      const isRootPage = pathname === '/'
      setShouldHide(isPowerWin && isRootPage)
    }
  }, [pathname])

  if (!isMobile) {
    return null
  }

  // Hide navbar on power.win root page
  if (shouldHide) {
    return null
  }

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 bg-black/30 backdrop-blur-md backdrop-brightness-75 border-t border-white/10 md:hidden">
      <div className="flex items-center justify-around h-16 px-2">
        {navItems.map((item) => {
          const isActive = pathname === item.href
          return (
            <Link
              key={item.label}
              href={item.href}
              className={cn(
                'flex flex-col items-center justify-center gap-1 flex-1 h-full transition-colors',
                'hover:bg-white/5 active:bg-white/10',
                isActive ? 'text-white' : 'text-gray-400'
              )}
            >
              <div
                className={cn(
                  'flex items-center justify-center transition-all w-5 h-5',
                  isActive ? 'opacity-100 scale-110' : 'opacity-70'
                )}
              >
                {item.icon}
              </div>
              <span
                className={cn(
                  'text-[10px] sm:text-xs font-medium transition-colors text-center leading-tight',
                  isActive ? 'text-white' : 'text-gray-400'
                )}
              >
                {item.label}
              </span>
            </Link>
          )
        })}
      </div>
    </nav>
  )
}
